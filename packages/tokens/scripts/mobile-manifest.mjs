/**
 * Classes DEFERRED from mobile emission (memo §2 m03.4, ratified 2026-08-04).
 * Easings are mobile-relevant (s166 review, decision #1347) with typed targets
 * (Compose CubicBezierEasing, iOS CAMediaTimingFunction); they are deferred because
 * typed emission is a consumer-API commitment better made with the mobile walk's
 * consumer in view. Font stacks genuinely do not map to mobile font APIs.
 */
export const MOBILE_DEFERRED_TYPES = {
  cubicBezier: 54,
  // s222-m01: 36 font stacks (was 14): the mono family beside the sans in ref, theme and sys, each brand's sans and mono,
  // and a family in each of the 13 type roles at both the text and sys layers.
  fontFamily: 36,
};

const membership = new Map();
for (const [cls, paths] of Object.entries(MOBILE_DIMENSION_CLASSES)) {
  for (const path of paths) membership.set(path, cls);
}

/**
 * s222-m01 (#2502 rulings 3 and 9): every brand's radius, in its base file under `radius.brand.<X>`, is a px dimension
 * whatever the brand is called, so the brands folder can grow without an edit here.
 */
const BRAND_RADIUS = /^radius\.brand\.[^.]+\.(control|small|large|card|pill)$/;

/** Class for a token path, or undefined if the path is not in the manifest. */
export function mobileDimensionClass(path) {
  const key = Array.isArray(path) ? path.join('.') : path;
  return membership.get(key) ?? (BRAND_RADIUS.test(key) ? 'spacing' : undefined);
}
